#!/usr/bin/env python3
"""Wrap each figure in figures/*.js in its own scope for the site: docs/assets/figures/<name>.js.

A figure is written for the hairline bench, where it is the only script; on the site several
share one page, so each runs inside a function and registers itself through hairline({...}).
"""
import glob
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "docs", "assets", "figures")
os.makedirs(OUT, exist_ok=True)
for src in sorted(glob.glob(os.path.join(ROOT, "figures", "*.js"))):
    body = open(src, encoding="utf-8").read().strip()
    open(os.path.join(OUT, os.path.basename(src)), "w", encoding="utf-8").write(
        "/* GENERATED by scripts/gen_figures.py from figures/%s */\n(() => {\n%s\n})();\n" % (os.path.basename(src), body))
    print("figure:", os.path.basename(src))
